defmodule AshGrpc.Resource.Info do
  @moduledoc """
  Reads a resource's `grpc do ... end` block: `grpc_proto_message/1` and
  `grpc_fields/1` (with `!` variants), generated by `Spark.InfoGenerator`.
  """

  use Spark.InfoGenerator, extension: AshGrpc.Resource, sections: [:grpc]

  alias Ash.Resource.Info
  alias AshGrpc.Resource.Transformers.ValidateFields

  @doc """
  The resource's `fields`, numbered or not, in declaration order. Without
  `fields` it is every public attribute, calculation (not on an embedded
  resource), aggregate and relationship that can go on the wire, less
  `hide_fields`.
  """
  @spec grpc_fields(Spark.Dsl.t() | module()) :: {:ok, list()}
  def grpc_fields(resource), do: {:ok, grpc_fields!(resource)}

  @spec grpc_fields!(Spark.Dsl.t() | module()) :: list()
  def grpc_fields!(resource) do
    case listed_fields(resource) do
      nil -> default_fields(resource)
      fields -> fields
    end
  end

  @doc "The names in `fields`, numbered or not, in declaration order."
  @spec grpc_field_names(Spark.Dsl.t() | module()) :: [atom()]
  def grpc_field_names(resource), do: AshGrpc.FieldNumbers.names(grpc_fields!(resource))

  @doc "The `fields` option as written, or nil when the resource exposes its public fields."
  @spec listed_fields(Spark.Dsl.t() | module()) :: list() | nil
  def listed_fields(resource), do: Spark.Dsl.Extension.get_opt(resource, [:grpc], :fields, nil)

  @doc "Every public attribute, calculation, aggregate and relationship name, in default order."
  @spec public_field_names(Spark.Dsl.t() | module()) :: [atom()]
  def public_field_names(resource) do
    calculations =
      if embedded?(resource), do: [], else: Info.public_calculations(resource)

    Enum.map(Info.public_attributes(resource), & &1.name) ++
      Enum.map(calculations, & &1.name) ++
      Enum.map(Info.public_aggregates(resource), & &1.name) ++
      Enum.map(Info.public_relationships(resource), & &1.name)
  end

  defp embedded?(resource), do: Info.embedded?(resource)

  defp default_fields(resource) do
    hidden = grpc_hide_fields!(resource)
    Enum.filter(public_field_names(resource) -- hidden, &exposable?(resource, &1))
  end

  defp exposable?(resource, name) do
    is_nil(ValidateFields.problem(resource, resource, name)) and
      case Info.relationship(resource, name) do
        nil -> true
        %{destination: destination} -> destination_exposed?(destination)
      end
  end

  defp destination_exposed?(destination),
    do: match?({:module, _}, Code.ensure_compiled(destination)) and exposed?(destination)

  @doc "Whether the resource uses `AshGrpc.Resource` and names a message."
  @spec exposed?(module()) :: boolean()
  def exposed?(resource) do
    AshGrpc.Resource in Spark.extensions(resource) and
      match?({:ok, _}, grpc_proto_message(resource))
  end

  @doc """
  The field (attribute, calculation or aggregate) behind a wire name, or nil.

  An aggregate is returned as a plain map with the keys the others share: its
  resolved `type` and `constraints`, `allow_nil?`, `public?`, `sensitive?` and
  `description`.
  """
  @spec field(Spark.Dsl.t() | module(), atom()) :: struct() | map() | nil
  def field(resource, name) do
    Info.attribute(resource, name) || Info.calculation(resource, name) ||
      aggregate_field(resource, name)
  end

  @doc "Whether the field is computed by a load rather than stored on the record."
  @spec loaded?(struct() | map()) :: boolean()
  def loaded?(field), do: not is_struct(field, Ash.Resource.Attribute)

  defp aggregate_field(resource, name) do
    with %Ash.Resource.Aggregate{} = aggregate <- Info.aggregate(resource, name) do
      {type, constraints} =
        case Ash.Query.Aggregate.aggregate_type(resource, aggregate) do
          {:ok, type, constraints} -> {type, constraints}
          _ -> {nil, []}
        end

      %{
        name: name,
        type: type,
        constraints: constraints,
        allow_nil?: aggregate.kind not in [:count, :exists, :list] and is_nil(aggregate.default),
        public?: aggregate.public?,
        sensitive?: aggregate.sensitive?,
        description: aggregate.description
      }
    end
  end

  @doc "Whether a field policy can hide the field from some caller (Ash expands `:*` to every non-key field)."
  @spec field_policy_covered?(module(), atom()) :: boolean()
  def field_policy_covered?(resource, name),
    do: Ash.Policy.Info.field_policies_for_field(resource, name) != nil
end
